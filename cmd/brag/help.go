package main

import "fmt"

func printUsage() {
	fmt.Println("brag - Staff-level professional accomplishment tracker")
	fmt.Println()
	fmt.Println("Usage: brag <command> [options]")
	fmt.Println()
	fmt.Println("Commands:")
	fmt.Println("  init           Initialize brag system (sets role title and start date)")
	fmt.Println("  add            Add a new accomplishment entry")
	fmt.Println("  update <id>    Update basic fields of an existing entry")
	fmt.Println("  enrich         Add Staff-level metrics to existing entries")
	fmt.Println("  list           List entries (default: last 7 days)")
	fmt.Println("  report         Generate summary report for review prep")
	fmt.Println("  remove <id>    Remove an entry by ID")
	fmt.Println("  clear          Clear all entries (with confirmation)")
	fmt.Println("  export         Export entries to file (csv, json, txt)")
	fmt.Println("  config         Update configuration (e.g., role start date)")
	fmt.Println("  help [cmd]     Show detailed help for a command")
	fmt.Println()
	fmt.Println("Examples:")
	fmt.Println("  brag add                          # Interactive daily capture")
	fmt.Println("  brag add --week 1 -b Delivery ... # Backfill week 1 entry")
	fmt.Println("  brag enrich                       # Weekly synthesis flow")
	fmt.Println("  brag enrich --id 6                # Re-enrich specific entry")
	fmt.Println("  brag list --month 3               # View month 3")
	fmt.Println("  brag report --month 3             # Generate month 3 report")
	fmt.Println()
	fmt.Println("Run 'brag help <command>' for detailed usage.")
}

