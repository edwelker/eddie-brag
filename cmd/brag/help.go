func printEnrichHelp() {
	fmt.Println("Usage: brag enrich [options]")
	fmt.Println()
	fmt.Println("Add Staff-level metrics to unenriched entries, or re-enrich existing entries.")
	fmt.Println()
	fmt.Println("Options:")
	fmt.Println("  --range string       Time range (e.g., 30d, 12w)")
	fmt.Println("  --id int             Enrich specific entry by ID")
	fmt.Println("  --pending            List unenriched entries without prompting")
	fmt.Println("  --hours string       Hours saved (e.g., 29.625, 90m, 2h)")
	fmt.Println("  --calc string        Calculation notes")
	fmt.Println("  --metric string      Business metric")
	fmt.Println("  --align string       Strategic alignment")
	fmt.Println("  --recognition string Peer recognition")
	fmt.Println("  --yes                Skip confirmation prompt")
	fmt.Println()
	fmt.Println("Enrichment Fields:")
	fmt.Println("  - Hours Saved (accepts: 1.5, 90m, 2h)")
	fmt.Println("  - Business Metric (e.g., \"Reduced latency by 200ms\")")
	fmt.Println("  - Strategic Alignment (e.g., \"Q2 OKR: Improve dev velocity\")")
	fmt.Println("  - Peer Recognition (e.g., \"Slack kudos from @manager\")")
	fmt.Println()
	fmt.Println("Examples:")
	fmt.Println("  brag enrich")
	fmt.Println("    # Find unenriched entries from last 7 days, prompt interactively")
	fmt.Println()
	fmt.Println("  brag enrich --id 6")
	fmt.Println("    # Re-enrich specific entry #6 (updates only fields you provide)")
	fmt.Println()
	fmt.Println("  brag enrich --pending")
	fmt.Println("    # List all unenriched entries without enriching")
	fmt.Println()
	fmt.Println("  brag enrich --id 2 --hours 29.625 --calc \"585 builds × 3 min\"")
	fmt.Println("    # Enrich entry #2 with flags (non-interactive)")
	fmt.Println()
	fmt.Println("  brag enrich --range 30d")
	fmt.Println("    # Enrich entries from last 30 days")
}

